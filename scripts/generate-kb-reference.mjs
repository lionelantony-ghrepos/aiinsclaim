#!/usr/bin/env node
/**
 * Writes committed snapshots under ljadoc/kb/generated from the current tree.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(repoRoot, "ljadoc", "kb", "generated");
const srcDir = path.join(repoRoot, "src");

function listTsSources(rootDir) {
  const out = [];
  const walk = (dir) => {
    for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, ent.name);
      if (ent.isDirectory()) walk(p);
      else if (
        (ent.name.endsWith(".ts") || ent.name.endsWith(".tsx")) &&
        !ent.name.endsWith(".test.ts") &&
        !ent.name.endsWith(".test.tsx")
      ) {
        out.push(path.relative(rootDir, p).replaceAll("\\", "/"));
      }
    }
  };
  if (fs.existsSync(rootDir)) walk(rootDir);
  return out.sort();
}

function schemaCatalog() {
  const schemasDir = path.join(srcDir, "lib", "schemas");
  const names = [];
  if (!fs.existsSync(schemasDir)) return names;
  const walk = (dir) => {
    for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, ent.name);
      if (ent.isDirectory()) walk(p);
      else if (ent.name.endsWith(".ts")) {
        const text = fs.readFileSync(p, "utf8");
        const rel = path.relative(schemasDir, p).replaceAll("\\", "/");
        for (const m of text.matchAll(/export const (\w+Schema)\s*=/g)) {
          names.push(`${rel}: ${m[1]}`);
        }
      }
    }
  };
  walk(schemasDir);
  return names.sort();
}

function writeIfChanged(file, contents) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const prev = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (prev === contents) return false;
  fs.writeFileSync(file, contents, "utf8");
  return true;
}

function main() {
  const pkg = JSON.parse(fs.readFileSync(path.join(repoRoot, "package.json"), "utf8"));
  const sources = listTsSources(srcDir);
  const pkgLines = [
    "# Package inventory",
    "",
    "Generated by `npm run docs:generate`. Not a substitute for as-built PBI pages.",
    "",
    `## ${pkg.name}`,
    "",
    `- Path: \`src/\``,
    `- Version: ${pkg.version}`,
    `- Sources:`,
  ];
  for (const s of sources.length ? sources : ["_(none)_"]) {
    pkgLines.push(typeof s === "string" && s.startsWith("_") ? ` ${s}` : ` - \`${s}\``);
  }
  pkgLines.push("");

  const schemaNames = schemaCatalog();
  const schemaLines = [
    "# Zod schema catalog",
    "",
    "Exported `*Schema` bindings under `src/lib/schemas/` (static scan).",
    "",
  ];
  if (schemaNames.length === 0) {
    schemaLines.push("_(no schemas exported yet — PBI-009+)_", "");
  } else {
    for (const n of schemaNames) schemaLines.push(`- ${n}`);
    schemaLines.push("");
  }

  const readme = [
    "# Generated reference",
    "",
    "Committed snapshots from `npm run docs:generate`. Do not hand-edit; regenerate instead.",
    "",
    "| File | Contents |",
    "| --- | --- |",
    "| [packages.md](packages.md) | App source inventory |",
    "| [schemas-catalog.md](schemas-catalog.md) | Zod `*Schema` exports |",
    "",
    "Engineering docs under `ljadoc/kb/` are **not** indexed into any future claims RAG corpus unless explicitly scheduled.",
    "",
  ].join("\n");

  writeIfChanged(path.join(outDir, "README.md"), readme);
  writeIfChanged(path.join(outDir, "packages.md"), `${pkgLines.join("\n")}\n`);
  writeIfChanged(path.join(outDir, "schemas-catalog.md"), schemaLines.join("\n"));
  console.log("Wrote ljadoc/kb/generated snapshots.");
}

main();
