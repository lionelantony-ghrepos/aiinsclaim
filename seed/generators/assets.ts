const MINIMAL_PDF = Buffer.from(
  "%PDF-1.1\n1 0 obj<<>>endobj\n2 0 obj<</Length 11>>stream\nBT /F1 12 Tf ET\nendstream\nendobj\nxref\n0 3\n0000000000 65535 f \n0000000009 00000 n \n0000000052 00000 n \ntrailer<</Size 3/Root 1 0 R>>\nstartxref\n109\n%%EOF\n",
);

export type SeedAsset = {
  fileName: string;
  mimeType: string;
  bytes: Buffer;
};

export async function ensureSeedAssets(): Promise<SeedAsset[]> {
  await fs.mkdir(ASSETS_DIR, { recursive: true });

  const assets: SeedAsset[] = [];
  for (let i = 0; i < 20; i += 1) {
    const isPdf = i % 3 === 0;
    const fileName = isPdf ? `sample-${i + 1}.pdf` : `sample-${i + 1}.jpg`;
    const mimeType = isPdf ? "application/pdf" : "image/jpeg";
    const bytes = isPdf ? MINIMAL_PDF : MINIMAL_JPEG;
    const filePath = path.join(ASSETS_DIR, fileName);

    try {
      await fs.access(filePath);
    } catch {
      await fs.writeFile(filePath, bytes);
    }

    assets.push({ fileName, mimeType, bytes });
  }

  return assets;
}
